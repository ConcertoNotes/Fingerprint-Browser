"""Fetch and parse Clash/Mihomo subscriptions without trusting them.

A subscription is a document written by a third party and fetched from a URL a
user pasted. Nothing in it is allowed to configure this computer: only the root
``proxies`` list is read, each entry is checked against a protocol whitelist and
reduced to plain values, and fields that name local files, interfaces or other
outbounds are dropped. Rules, DNS, TUN, controllers and scripts are ignored —
the runtime configuration is always generated by :mod:`mihomo_manager`.

Fetching is HTTPS only and guarded at the socket: every connection, including
each redirect hop, resolves the host itself and refuses unless *all* of its
addresses are public. Checking a name and then letting a client resolve it again
would leave a DNS-rebinding window; here the validated address is the one dialed.
The fetch is deliberately direct (``trust_env`` has no meaning for httpcore), so
an environment proxy cannot bypass the address check.
"""

from __future__ import annotations

import asyncio
import base64
import binascii
import hashlib
import ipaddress
import json
import re
import ssl
import unicodedata
import zlib
from collections.abc import Awaitable, Callable, Iterable
from dataclasses import dataclass, field
from typing import Any
from urllib.parse import urljoin, urlsplit

import httpcore
import httpx
import yaml

# Panels such as V2Board and SSPanel choose the response format from the client's
# User-Agent; this one asks for Clash/Mihomo YAML instead of Base64 URI lists.
SUBSCRIPTION_USER_AGENT = "clash.meta/v1.18.0"
MAX_DOWNLOAD_BYTES = 10 * 1024 * 1024
MAX_DECOMPRESSED_BYTES = 20 * 1024 * 1024
FETCH_TIMEOUT = 30.0
MAX_REDIRECTS = 3
MAX_NODES = 2000
MAX_YAML_NODES = 500_000
MAX_YAML_ALIASES = 200
MAX_NODE_JSON = 32 * 1024
MAX_STRING = 8192
MAX_DEPTH = 5

# Protocol whitelist and the fields each needs to be usable. Everything that
# Mihomo can dial as an outbound to a remote server; no local or meta types.
REQUIRED_FIELDS: dict[str, tuple[str, ...]] = {
    "ss": ("cipher", "password"),
    "ssr": ("cipher", "password", "obfs", "protocol"),
    "vmess": ("uuid",),
    "vless": ("uuid",),
    "trojan": ("password",),
    "hysteria": (),
    "hysteria2": ("password",),
    "tuic": (),
    "anytls": ("password",),
    "snell": ("psk",),
    "wireguard": ("private-key",),
    "socks5": (),
    "http": (),
}
# Fields that would reach outside the single outbound this node describes:
# chaining through another named proxy, binding to a host interface or routing
# table, or loading a provider.
DROPPED_FIELDS = frozenset(
    {"dialer-proxy", "interface-name", "routing-mark", "provider", "name", "type"}
)
# Fields that Mihomo reads as *paths* unless they hold inline PEM.
FILE_FIELDS = frozenset({"ca", "certificate", "private-key", "cert", "key", "ca-path"})
_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$")
_HOST = re.compile(r"^[A-Za-z0-9._:\[\]-]{1,253}$")
_URI_LINE = re.compile(
    r"^(ss|ssr|vmess|vless|trojan|hysteria2?|hy2|tuic|anytls|socks5?|https?)://", re.I
)


class SubscriptionError(ValueError):
    """A subscription could not be used. ``code`` is stable; the message is safe."""

    def __init__(self, code: str, message: str):
        self.code = code
        super().__init__(message)


@dataclass
class ParsedNode:
    name: str
    protocol: str
    server: str
    port: int
    config: dict[str, Any]
    key: str = ""
    insecure: bool = False
    # Panels list traffic, expiry or their website as fake "nodes". They stay in
    # the subscription for reference but are never checked, mapped or bound.
    informational: bool = False

    @property
    def entry(self) -> str:
        host = f"[{self.server}]" if ":" in self.server else self.server
        return f"{host}:{self.port}"


@dataclass
class ParsedSubscription:
    nodes: list[ParsedNode]
    warnings: list[dict[str, Any]] = field(default_factory=list)
    usage: dict[str, int] | None = None
    suggested_name: str | None = None


# --- Fetching ---------------------------------------------------------------


def address_is_public(address: str) -> bool:
    """Whether a destination may be fetched: global unicast, never local or reserved."""
    try:
        ip = ipaddress.ip_address(address.split("%", 1)[0])
    except ValueError:
        return False
    if isinstance(ip, ipaddress.IPv6Address) and ip.ipv4_mapped is not None:
        ip = ip.ipv4_mapped
    return bool(ip.is_global) and not ip.is_multicast and not ip.is_reserved


Resolver = Callable[[str, int], Awaitable[list[str]]]
AddressPolicy = Callable[[str], bool]


async def _system_resolve(host: str, port: int) -> list[str]:
    loop = asyncio.get_running_loop()
    infos = await loop.getaddrinfo(host, port, type=0, proto=6)
    return list(dict.fromkeys(str(info[4][0]) for info in infos))


class GuardedBackend(httpcore.AsyncNetworkBackend):
    """Dial only addresses the policy accepts, after resolving them ourselves."""

    def __init__(
        self,
        resolver: Resolver = _system_resolve,
        policy: AddressPolicy = address_is_public,
        inner: httpcore.AsyncNetworkBackend | None = None,
    ):
        self._resolver = resolver
        self._policy = policy
        self._inner = inner or httpcore.AnyIOBackend()

    async def connect_tcp(
        self,
        host: str,
        port: int,
        timeout: float | None = None,
        local_address: str | None = None,
        socket_options: Iterable[Any] | None = None,
    ) -> httpcore.AsyncNetworkStream:
        literal = host.strip("[]")
        try:
            ipaddress.ip_address(literal)
            addresses = [literal]
        except ValueError:
            try:
                addresses = await self._resolver(host, port)
            except OSError:
                raise SubscriptionError(
                    "dns_failed", "The subscription host could not be resolved."
                ) from None
        # Every answer must be acceptable: a name that resolves to one public and
        # one private address is exactly how rebinding is staged.
        if not addresses or not all(self._policy(address) for address in addresses):
            raise SubscriptionError(
                "blocked_address",
                "The subscription host resolves to a private, local or reserved address.",
            )
        return await self._inner.connect_tcp(
            addresses[0], port, timeout, local_address, socket_options
        )

    async def connect_unix_socket(self, *args: Any, **kwargs: Any) -> httpcore.AsyncNetworkStream:
        raise SubscriptionError("blocked_address", "Unix sockets are not allowed.")

    async def sleep(self, seconds: float) -> None:
        await self._inner.sleep(seconds)


def validate_subscription_url(url: str) -> str:
    """Normalize and check a pasted URL before any network access."""
    url = (url or "").strip()
    if len(url) > 4096 or any(ch.isspace() or ord(ch) < 32 for ch in url):
        raise SubscriptionError("invalid_url", "Enter a valid HTTPS subscription URL.")
    try:
        parts = urlsplit(url)
        port = parts.port
    except ValueError:
        raise SubscriptionError("invalid_url", "Enter a valid HTTPS subscription URL.") from None
    if parts.scheme.lower() != "https":
        raise SubscriptionError("https_required", "Subscription URLs must use HTTPS.")
    if not parts.hostname or parts.username or parts.password:
        raise SubscriptionError(
            "invalid_url", "Enter a valid HTTPS subscription URL without credentials."
        )
    if port is not None and not 1 <= port <= 65535:
        raise SubscriptionError("invalid_url", "Enter a valid HTTPS subscription URL.")
    return url


def mask_url(url: str) -> str:
    """Host only. Paths and queries of subscription URLs usually carry the token."""
    try:
        parts = urlsplit(url)
    except ValueError:
        return "https://…"
    host = parts.hostname or "…"
    return f"https://{host}/…"


def parse_usage(header: str | None) -> dict[str, int] | None:
    """``subscription-userinfo: upload=1; download=2; total=3; expire=4``."""
    if not header or len(header) > 512:
        return None
    usage: dict[str, int] = {}
    for part in header.split(";"):
        key, _, value = part.strip().partition("=")
        key = key.strip().lower()
        if key in {"upload", "download", "total", "expire"}:
            try:
                number = int(float(value.strip()))
            except ValueError:
                continue
            if 0 <= number < 2**63:
                usage[key] = number
    return usage or None


def _filename_hint(header: str | None) -> str | None:
    if not header:
        return None
    match = re.search(r"filename\*=UTF-8''([^;]+)|filename=\"?([^\";]+)", header, re.I)
    if not match:
        return None
    from urllib.parse import unquote

    name = unquote(match.group(1) or match.group(2) or "").strip()
    name = re.sub(r"\.(ya?ml|txt|conf)$", "", name, flags=re.I)
    return _clean_text(name, 64) or None


@dataclass
class FetchedSubscription:
    content: bytes
    usage: dict[str, int] | None
    suggested_name: str | None


def _decode_body(body: bytes, encoding: str) -> bytes:
    encoding = encoding.strip().lower()
    if encoding in {"", "identity"}:
        return body
    if encoding not in {"gzip", "deflate", "x-gzip"}:
        raise SubscriptionError("unsupported_encoding", "The response encoding is unsupported.")
    wbits = 16 + zlib.MAX_WBITS if "gzip" in encoding else zlib.MAX_WBITS
    decompressor = zlib.decompressobj(wbits)
    try:
        data = decompressor.decompress(body, MAX_DECOMPRESSED_BYTES + 1)
    except zlib.error:
        raise SubscriptionError("invalid_response", "The response could not be decoded.") from None
    if len(data) > MAX_DECOMPRESSED_BYTES or decompressor.unconsumed_tail:
        raise SubscriptionError("too_large", "The subscription is larger than 20 MB.")
    return data


async def fetch_subscription(
    url: str,
    *,
    backend: httpcore.AsyncNetworkBackend | None = None,
    ssl_context: ssl.SSLContext | None = None,
    timeout: float = FETCH_TIMEOUT,
) -> FetchedSubscription:
    """Download a subscription with redirects, sizes and addresses all bounded."""
    url = validate_subscription_url(url)
    context = ssl_context or httpx.create_ssl_context()
    try:
        return await asyncio.wait_for(_fetch(url, backend, context), timeout=timeout)
    except asyncio.TimeoutError:
        raise SubscriptionError(
            "timeout", "The subscription server did not answer in time."
        ) from None


async def _fetch(
    url: str, backend: httpcore.AsyncNetworkBackend | None, context: ssl.SSLContext
) -> FetchedSubscription:
    headers = [
        (b"User-Agent", SUBSCRIPTION_USER_AGENT.encode()),
        (b"Accept", b"application/yaml, text/yaml, text/plain, */*"),
        (b"Accept-Encoding", b"gzip, identity"),
    ]
    async with httpcore.AsyncConnectionPool(
        ssl_context=context,
        network_backend=backend or GuardedBackend(),
        max_connections=1,
    ) as pool:
        for _ in range(MAX_REDIRECTS + 1):
            try:
                async with pool.stream("GET", url, headers=headers) as response:
                    status = response.status
                    meta = {
                        key.decode("latin-1").lower(): value.decode("latin-1")
                        for key, value in response.headers
                    }
                    if status in {301, 302, 303, 307, 308}:
                        location = meta.get("location")
                        if not location:
                            raise SubscriptionError(
                                "invalid_response", "The server sent an incomplete redirect."
                            )
                        url = validate_subscription_url(urljoin(url, location))
                        continue
                    if status != 200:
                        raise SubscriptionError(
                            "http_status", f"The subscription server answered HTTP {status}."
                        )
                    declared = meta.get("content-length", "")
                    if declared.isdigit() and int(declared) > MAX_DOWNLOAD_BYTES:
                        raise SubscriptionError(
                            "too_large", "The subscription is larger than 10 MB."
                        )
                    body = bytearray()
                    async for chunk in response.aiter_stream():
                        body.extend(chunk)
                        if len(body) > MAX_DOWNLOAD_BYTES:
                            raise SubscriptionError(
                                "too_large", "The subscription is larger than 10 MB."
                            )
                    content = _decode_body(bytes(body), meta.get("content-encoding", ""))
                    return FetchedSubscription(
                        content=content,
                        usage=parse_usage(meta.get("subscription-userinfo")),
                        suggested_name=_filename_hint(meta.get("content-disposition")),
                    )
            except SubscriptionError:
                raise
            except ssl.SSLError:
                raise SubscriptionError(
                    "tls_failed", "The subscription server's TLS certificate could not be verified."
                ) from None
            except (httpcore.TimeoutException, TimeoutError):
                raise SubscriptionError(
                    "timeout", "The subscription server did not answer in time."
                ) from None
            except (httpcore.NetworkError, httpcore.ProtocolError, OSError) as exc:
                # Transport errors can embed the URL; report the class only.
                raise SubscriptionError(
                    "connection_failed",
                    f"The subscription server could not be reached ({type(exc).__name__}).",
                ) from None
    raise SubscriptionError("too_many_redirects", "The subscription redirected too many times.")


# --- Parsing ----------------------------------------------------------------


class _BoundedLoader(yaml.SafeLoader):
    """The safe loader with a budget, so aliases and huge trees cannot exhaust memory."""

    def __init__(self, stream: str):
        super().__init__(stream)
        self._nodes = 0
        self._aliases = 0

    def compose_node(self, parent: Any, index: Any) -> Any:  # type: ignore[override]
        if self.check_event(yaml.AliasEvent):
            self._aliases += 1
            if self._aliases > MAX_YAML_ALIASES:
                raise SubscriptionError("yaml_too_complex", "The YAML uses too many aliases.")
        self._nodes += 1
        if self._nodes > MAX_YAML_NODES:
            raise SubscriptionError("yaml_too_complex", "The YAML document is too large.")
        return super().compose_node(parent, index)


def _clean_text(value: Any, limit: int) -> str:
    text = unicodedata.normalize("NFC", str(value))
    text = "".join(ch for ch in text if not unicodedata.category(ch).startswith("C"))
    return " ".join(text.split())[:limit]


def _plain(value: Any, depth: int = 0) -> Any:
    """Reduce a YAML value to JSON-safe plain data, or raise ValueError."""
    if depth > MAX_DEPTH:
        raise ValueError("nested too deeply")
    if value is None or isinstance(value, (bool, int, float)):
        if isinstance(value, float) and value != value:  # NaN
            raise ValueError("invalid number")
        return value
    if isinstance(value, str):
        if len(value) > MAX_STRING or "\x00" in value:
            raise ValueError("invalid string")
        return value
    if isinstance(value, list):
        if len(value) > 256:
            raise ValueError("list too long")
        return [_plain(item, depth + 1) for item in value]
    if isinstance(value, dict):
        if len(value) > 128:
            raise ValueError("mapping too large")
        result = {}
        for key, item in value.items():
            if not isinstance(key, str) or not _KEY.match(key):
                raise ValueError("invalid key")
            result[key] = _plain(item, depth + 1)
        return result
    raise ValueError("unsupported value type")


def _is_pem(value: Any) -> bool:
    return isinstance(value, str) and value.lstrip().startswith("-----BEGIN ")


def _strip_file_fields(protocol: str, value: Any) -> Any:
    if isinstance(value, dict):
        return {
            key: _strip_file_fields(protocol, item)
            for key, item in value.items()
            if not (
                key in FILE_FIELDS
                and not _is_pem(item)
                and not (protocol == "wireguard" and key == "private-key")
            )
        }
    if isinstance(value, list):
        return [_strip_file_fields(protocol, item) for item in value]
    return value


def _contains_skip_verify(value: Any) -> bool:
    if isinstance(value, dict):
        return any(
            (key == "skip-cert-verify" and item is True) or _contains_skip_verify(item)
            for key, item in value.items()
        )
    if isinstance(value, list):
        return any(_contains_skip_verify(item) for item in value)
    return False


def validate_node(raw: Any) -> ParsedNode:
    """One ``proxies`` entry, reduced to a safe outbound, or ValueError(reason)."""
    if not isinstance(raw, dict):
        raise ValueError("entry is not a mapping")
    protocol = str(raw.get("type", "")).strip().lower()
    if protocol not in REQUIRED_FIELDS:
        raise ValueError("unsupported protocol")
    server = raw.get("server")
    if not isinstance(server, str) or not _HOST.match(server.strip()):
        raise ValueError("missing or invalid server")
    server = server.strip().strip("[]")
    if "://" in server or "/" in server:
        raise ValueError("missing or invalid server")
    port = raw.get("port")
    if isinstance(port, str) and port.strip().isdigit():
        port = int(port.strip())
    if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
        raise ValueError("missing or invalid port")
    for required in REQUIRED_FIELDS[protocol]:
        if raw.get(required) in (None, ""):
            raise ValueError(f"missing {required}")
    if protocol == "tuic" and not (raw.get("uuid") or raw.get("token")):
        raise ValueError("missing uuid or token")
    try:
        config = _plain({k: v for k, v in raw.items() if k not in DROPPED_FIELDS})
    except ValueError as exc:
        raise ValueError(f"invalid field value ({exc})") from None
    config = _strip_file_fields(protocol, config)
    config["server"] = server
    config["port"] = port
    if len(json.dumps(config, ensure_ascii=False)) > MAX_NODE_JSON:
        raise ValueError("entry is too large")
    name = _clean_text(raw.get("name") or "", 128) or f"{protocol} {server}:{port}"
    return ParsedNode(
        name=name,
        protocol=protocol,
        server=server,
        port=port,
        config=config,
        insecure=_contains_skip_verify(config),
    )


def node_key(node: ParsedNode) -> str:
    """Stable identity within one subscription, never derived from secrets."""
    material = "|".join((node.protocol, node.server.lower(), str(node.port), node.name.casefold()))
    return hashlib.sha256(material.encode()).hexdigest()[:32]


def _looks_like_base64_list(text: str) -> bool:
    compact = "".join(text.split())
    if len(compact) < 16 or not re.fullmatch(r"[A-Za-z0-9+/=_-]+", compact):
        return False
    try:
        decoded = base64.b64decode(compact + "=" * (-len(compact) % 4), altchars=b"-_")
    except (binascii.Error, ValueError):
        return False
    return b"://" in decoded


def parse_subscription(content: bytes | str) -> ParsedSubscription:
    """Parse Clash/Mihomo YAML into validated nodes, or raise SubscriptionError."""
    if isinstance(content, bytes):
        if len(content) > MAX_DECOMPRESSED_BYTES:
            raise SubscriptionError("too_large", "The subscription is larger than 20 MB.")
        try:
            text = content.decode("utf-8-sig")
        except UnicodeDecodeError:
            raise SubscriptionError(
                "invalid_encoding", "The subscription is not UTF-8 text."
            ) from None
    else:
        text = content
    if not text.strip():
        raise SubscriptionError("empty", "The subscription is empty.")
    from .network_uri import decode_link_list

    links = decode_link_list(text)
    if links is not None:
        # Share-link lists and Base64 subscriptions become the same mappings a
        # Clash document would hold, then go through the same validation.
        return _collect(_links_to_mappings(links))
    try:
        loader = _BoundedLoader(text)
        try:
            document = loader.get_single_data()
        finally:
            loader.dispose()
    except SubscriptionError:
        raise
    except yaml.YAMLError:
        # Problem marks quote the input, which may contain credentials.
        raise SubscriptionError("invalid_yaml", "The subscription is not valid YAML.") from None
    if not isinstance(document, dict):
        raise SubscriptionError(
            "invalid_yaml", "The subscription is not a Clash/Mihomo configuration."
        )
    proxies = document.get("proxies")
    if not proxies:
        if document.get("proxy-providers"):
            raise SubscriptionError(
                "providers_only",
                "This configuration only references proxy-providers and contains no inline "
                "proxies. Provider subscriptions are not supported yet; import the provider's "
                "own URL instead.",
            )
        raise SubscriptionError("no_proxies", "The configuration contains no proxies.")
    if not isinstance(proxies, list):
        raise SubscriptionError("invalid_yaml", "The proxies section is not a list.")
    if len(proxies) > MAX_NODES:
        raise SubscriptionError(
            "too_many_nodes", f"A subscription can contain at most {MAX_NODES} nodes."
        )

    return _collect([(index, raw, None) for index, raw in enumerate(proxies, start=1)])


def _links_to_mappings(lines: list[str]) -> list[tuple[int, Any, str | None]]:
    from .network_uri import LinkError, parse_link

    if len(lines) > MAX_NODES:
        raise SubscriptionError(
            "too_many_nodes", f"A subscription can contain at most {MAX_NODES} nodes."
        )
    mappings: list[tuple[int, Any, str | None]] = []
    for index, line in enumerate(lines, start=1):
        try:
            mappings.append((index, parse_link(line), None))
        except LinkError as exc:
            mappings.append((index, None, str(exc)))
    return mappings


# Names panels use for pseudo-nodes that carry account information.
_INFORMATIONAL = re.compile(
    r"剩余流量|剩餘流量|到期|過期|过期|更新時間|更新时间|官网|官網|网址|網址|下次重置|套餐|"
    r"\bexpire|\btraffic\b|\breset\b|website",
    re.I,
)


def is_informational(name: str) -> bool:
    return bool(_INFORMATIONAL.search(name))


def _collect(entries: list[tuple[int, Any, str | None]]) -> ParsedSubscription:
    nodes: list[ParsedNode] = []
    warnings: list[dict[str, Any]] = []
    seen: dict[str, int] = {}
    for index, raw, failure in entries:
        if failure is not None:
            warnings.append({"index": index, "reason": failure})
            continue
        try:
            node = validate_node(raw)
        except ValueError as exc:
            # The reason never contains a value from the entry.
            warnings.append({"index": index, "reason": str(exc)})
            continue
        node.informational = is_informational(node.name)
        key = node_key(node)
        seen[key] = seen.get(key, 0) + 1
        node.key = key if seen[key] == 1 else f"{key}#{seen[key]}"
        nodes.append(node)
    if not any(not node.informational for node in nodes):
        raise SubscriptionError(
            "no_valid_proxies", "None of the proxies in this subscription can be used."
        )
    return ParsedSubscription(nodes=nodes, warnings=warnings)
